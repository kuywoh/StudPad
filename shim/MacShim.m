    });
}

static uint64_t guest_entry_offset(const struct mach_header_64 *header) {
    const uint8_t *p = (const uint8_t *)(header + 1);
    for (uint32_t i = 0; i < header->ncmds; i++) {
        const struct load_command *lc = (const void *)p;
        if (lc->cmdsize < sizeof *lc) return 0;
        if (lc->cmd == LC_MAIN) return ((const struct entry_point_command *)lc)->entryoff;
        p += lc->cmdsize;
    }
    return 0;
}

static const struct mach_header_64 *find_guest(uint32_t first) {
    uint32_t count = _dyld_image_count();
    for (uint32_t i = first; i < count; i++) {
        const char *name = _dyld_get_image_name(i);
        if (name && strstr(name, "/Frameworks/StudioKit")) {
            return (const struct mach_header_64 *)_dyld_get_image_header(i);
        }
    }
    return NULL;
}

