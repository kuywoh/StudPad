- (void)finishLaunching {
    if (_msFinishedLaunching) return;
    _msFinishedLaunching = YES;
    studpad_log("[shim] finishLaunching");
    // Qt registers for input and screen changes from the delegate's
    // applicationDidFinishLaunching, exactly as on macOS. Skipping it is why a shimmed app gets no
    // input at all.
    id delegate = _msDelegate;
    SEL selector = @selector(applicationDidFinishLaunching:);
    if (delegate && [delegate respondsToSelector:selector]) {
        NSNotification *note = [NSNotification
            notificationWithName:@"NSApplicationDidFinishLaunchingNotification"
                          object:self];
        // NSApplicationDelegate, not UIApplicationDelegate: the iOS SDK declares that selector on
        // UIApplication, so it is sent through the runtime to avoid binding the wrong signature.
        ((void (*)(id, SEL, id))objc_msgSend)(delegate, selector, note);
    }
    [[NSNotificationCenter defaultCenter]
        postNotificationName:@"NSApplicationDidFinishLaunchingNotification"
                      object:self];
}

