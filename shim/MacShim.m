static int gLogFd = -1;
static studpad_log_hook gHostLog = NULL;
static long gStubLines = 0;
static long gStubTotal = 0;

static NSString *studpad_log_path(void) {
    static NSString *path = nil;
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        NSString *docs = NSSearchPathForDirectoriesInDomains(NSDocumentDirectory, NSUserDomainMask,
                                                             YES).firstObject;
        path = [docs stringByAppendingPathComponent:@"studio.log"];
    });
    return path;
}

static void studpad_open_log(void) {
    if (gLogFd >= 0) return;
    gLogFd = open(studpad_log_path().fileSystemRepresentation, O_WRONLY | O_CREAT | O_APPEND, 0644);
    if (gLogFd >= 0) {
        dup2(gLogFd, STDOUT_FILENO);
        dup2(gLogFd, STDERR_FILENO);
        setvbuf(stdout, NULL, _IONBF, 0);
        setvbuf(stderr, NULL, _IONBF, 0);
    }
}

void studpad_set_log_hook(studpad_log_hook hook) { gHostLog = hook; }

const char *studpad_log_path_c(void) { return studpad_log_path().fileSystemRepresentation; }

void studpad_log(const char *fmt, ...) {
    studpad_open_log();
    char line[2048];
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(line, sizeof line, fmt, ap);
    va_end(ap);
    if (n < 0) return;
    size_t len = (size_t)n < sizeof line - 2 ? (size_t)n : sizeof line - 2;
    line[len++] = '\n';
    line[len] = '\0';
    if (gLogFd >= 0) {
        ssize_t ignored = write(gLogFd, line, len);
        (void)ignored;
    }
    if (gHostLog) gHostLog(line);
}

// A few thousand stubs logged in full would bury the useful lines, so the first calls are shown and
// the rest are only counted.
void *studpad_stub(const char *name) {
    gStubTotal++;
    if (gStubLines < 3000) {
        gStubLines++;
        studpad_log("[stub] %s()", name);
    } else if (gStubTotal == 3001) {
        studpad_log("[stub] further stub calls are only counted");
    }
    return NULL;
}

void *studpad_stub_asm(void) {
    return studpad_stub("(asm alias)");
}

long studpad_stub_count(void) { return gStubTotal; }

